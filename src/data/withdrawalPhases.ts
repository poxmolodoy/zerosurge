export interface WithdrawalPhaseInfo {
  dayRange: string;
  title: string;
  symptomExplanation: string;
  scientificFact: string;
  recommendedAction: string;
}

export function getWithdrawalPhase(days: number): WithdrawalPhaseInfo {
  if (days < 1) {
    return {
      dayRange: 'День 1 (Первые 24 часа)',
      title: 'Начало снижения концентрации кофеина в плазме',
      symptomExplanation:
        'Вы можете чувствовать тяжесть в голове, сонливость и сильное желание выпить привычную банку. По данным обзоров (Juliano & Griffiths, 2004), первые симптомы отмены манифестируют через 12–24 часа после последней дозы.',
      scientificFact:
        'Период полувыведения кофеина составляет 3–7 часов. К концу первых суток почки практически полностью элиминируют циркулирующий кофеин и его метаболиты.',
      recommendedAction:
        'Пейте больше чистой воды, избегайте стрессовых перегрузок и прилягте отдохнуть при выраженной сонливости.',
    };
  }

  if (days <= 3) {
    return {
      dayRange: 'Дни 2–3 (Пик синдрома отмены)',
      title: 'Пик абстиненции (20–51 ч) и церебральная вазодилатация',
      symptomExplanation:
        'Головная боль, упадок сил и раздражительность достигают максимальной выраженности на 20–51 час воздержания. Это связано с реактивным расширением мозговых сосудов (приток крови увеличивается до +30% после хронического спазма).',
      scientificFact:
        'По данным метаанализов, типичная продолжительность острых проявлений абстиненции составляет от 2 до 9 дней с пиком на 1–2 сутки.',
      recommendedAction:
        'Холодный компресс на область лба, прогулка на свежем воздухе и техника глубокого дыхания 4-4-4-4.',
    };
  }

  if (days <= 7) {
    return {
      dayRange: 'Дни 4–7 (Стихание острых симптомов)',
      title: 'Угасание головной боли и перестройка сна',
      symptomExplanation:
        'Острые сосудистые головные боли отступают. Основной вызов в эти дни — ситуационные поведенческие триггеры (поездка за рулем, начало рабочего дня). Может сохраняться дневная сонливость.',
      scientificFact:
        'Постепенно удлиняются фазы медленноволнового глубокого сна (NREM), ответственные за физическое восстановление тканей.',
      recommendedAction:
        'Замените банку энергетика сильногазированной минеральной водой с лимоном для удовлетворения сенсорной привычки.',
    };
  }

  if (days <= 14) {
    return {
      dayRange: 'Дни 8–14 (Нормализация чувствительности)',
      title: 'Регуляция аденозиновых рецепторов',
      symptomExplanation:
        'Физические симптомы отмены полностью купированы. Возвращается ровная утренняя ясность. Важно не поддаться мысли «от одной банки ничего не будет».',
      scientificFact:
        'Плотность аденозиновых рецепторов A1/A2A снижается до исходного физиологического уровня (даунрегуляция толерантности).',
      recommendedAction:
        'Зафиксируйте успехи в дневнике самочувствия и оцените уровень естественной энергии.',
    };
  }

  return {
    dayRange: 'День 15+ (Стойкая адаптация)',
    title: 'Поведенческая автономия',
    symptomExplanation:
      'Организм полностью адаптировался к жизни без стимулятора. Эпизодические позывы носят исключительно психологический характер.',
    scientificFact:
      'Сердечно-сосудистая система и циркадный ритм кортизола функционируют в индивидуальном физиологическом оптимуме.',
    recommendedAction: 'Используйте технику Urge Surfing при возникновении стрессовых ситуаций.',
  };
}
