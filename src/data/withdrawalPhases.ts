export interface WithdrawalPhaseInfo {
  dayRange: string;
  title: string;
  symptomExplanation: string;
  scientificFact: string;
  recommendedAction: string;
}

export function getWithdrawalPhase(days: number): WithdrawalPhaseInfo {
  if (days < 1) {
    return {
      dayRange: 'День 1 (Первые 24 часа)',
      title: 'Начало детоксикации и спад адреналина',
      symptomExplanation:
        'Вы можете чувствовать тяжесть в голове, туманность мыслей и сильное желание зайти в магазин. Это падение уровня адреналина, который энергетик искусственно подстегивал.',
      scientificFact:
        'Период полувыведения кофеина уже завершается. Почки активно фильтруют таурин и ароматизаторы.',
      recommendedAction:
        'Выпейте стакан ледяной воды и сделайте 10 глубоких вдохов. Первые сутки — самые непривычные.',
    };
  }

  if (days <= 3) {
    return {
      dayRange: 'Дни 2–3 (Пик синдрома отмены)',
      title: 'Церебральная вазодилатация (Расширение сосудов мозга)',
      symptomExplanation:
        'Головная боль, раздражительность или упадок сил на 2-3 день — это НЕ болезнь и НЕ повод сорваться! Это ваши сосуды мозга, которые месяцами были спазмированы кофеином, наконец расслабились и расширились. Усиленный приток крови вызывает временную пульсирующую боль.',
      scientificFact:
        'Кровоток в коре головного мозга увеличивается на 25–30%. Этот пик длится всего 48 часов и бесследно проходит.',
      recommendedAction:
        'Холодный компресс на лоб, контрастное умывание и 10 минут отдыха с закрытыми глазами.',
    };
  }

  if (days <= 7) {
    return {
      dayRange: 'Дни 4–7 (Переломный момент)',
      title: 'Угасание сосудистого спазма и перестройка сна',
      symptomExplanation:
        'Головная боль отступает. Главный враг сейчас — привычка пить банку в определенные часы (триггеры: за рулем, на работе, за компьютером). Может ощущаться дневная сонливость, так как мозг учится спать глубоко.',
      scientificFact:
        'Эпифиз восстанавливает естественный ритм мелатонина. Фазы глубокого дельта-сна удлиняются.',
      recommendedAction:
        'Замените банку на сильногазированную минералку со льдом или холодный травяной чай с лимоном.',
    };
  }

  if (days <= 14) {
    return {
      dayRange: 'Дни 8–14 (Очищение рецепторов)',
      title: 'Даунрегуляция аденозиновых рецепторов',
      symptomExplanation:
        'Физическая ломка полностью позади. Возникают коварные мысли: «Я уже доказал себе, что могу, от одной баночки ничего не будет». Не верьте этой уловке мозга!',
      scientificFact:
        'Лишние аденозиновые рецепторы разрушаются. Появляется чистая утренняя бодрость без учащенного пульса.',
      recommendedAction:
        'Вспомните, сколько денег и здоровья уже спасено. Запустите 10-минутный таймер тяги ниже.',
    };
  }

  return {
    dayRange: 'День 15+ (Стойкая свобода)',
    title: 'Психологическая автономия',
    symptomExplanation:
      'Тяга сейчас носит чисто психологический или стрессовый характер. Тело полностью очищено и не нуждается в стимуляторе.',
    scientificFact:
      'Инсулиновая чувствительность и миокард работают в оптимальном здоровом режиме.',
    recommendedAction:
      'Используйте технику дыхания по квадрату. Сделайте 15 приседаний, чтобы переключить нервную систему.',
  };
}
